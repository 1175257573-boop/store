def sql(stmt: str) -> str:
    """执行 SQL 并返回输出文本。"""
    p = subprocess.run(
        [MYSQL, "-uroot", "-p123456", "--default-character-set=utf8mb4",
         "-e", f"USE {DB}; {stmt}"],
        capture_output=True)
    out = p.stdout.decode("utf-8", errors="replace")
    if p.returncode != 0:
        print("  [SQL 失败]", p.stderr.decode("utf-8", errors="replace")[:300])
    return out


def run_sql_file(stmt: str) -> None:
    """把长 SQL 写文件再导入。

    Windows 命令行有 32K 限制，100 条商品带 SKU 的 INSERT
    直接走 -e 会被 shell 拒绝（WinError 206），必须走文件。
    """
    f = os.path.join(tempfile.gettempdir(), f"seed_{uuid.uuid4().hex[:8]}.sql")
    with io.open(f, "w", encoding="utf-8") as fh:
        fh.write(f"USE {DB};\n")
        fh.write(stmt)
    with io.open(f, "rb") as fh:
        p = subprocess.run(
            [MYSQL, "-uroot", "-p123456", "--default-character-set=utf8mb4"],
            stdin=fh, capture_output=True)
    os.remove(f)
    if p.returncode != 0:
        print("  [导入失败]", p.stderr.decode("utf-8", errors="replace")[:300])


def esc(v) -> str:
    """转义 SQL 字符串字面量。"""
    if v is None:
        return "NULL"
    return "'" + str(v).replace("\\", "\\\\").replace("'", "''") + "'"


