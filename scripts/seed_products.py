def dec(v) -> str:
    """格式化为合法的 SQL DECIMAL 字面量。"""
    return f"{float(v):.2f}"


def build():
    """生成 SQL 行。返回 (product_rows, 统计)。

    注意两个易错点：
    1. merchant_id 必须写 NULL —— 本批商品是「平台自建」，
       用分类 id 顶替会插入错误归属。
    2. DECIMAL 字面量只能有一个小数点，必须用 dec() 格式化，
       不能 f"{price}.00"（price 已是浮点时会变成 5373.75.00）。
    """
    prod_rows = []
    stats = {c: 0 for c in range(1, 9)}

    for idx, (cid, cat_name, model, specs, price, desc) in enumerate(GOODS, 1):
        zh, en = BRANDS[cid][idx % len(BRANDS[cid])]
        name = f"{zh} {cat_name} {model} {specs[0]}"
        origin = round(price / 0.8, 2)          # 原价 = 售价 / 0.8，形成 8 折展示
        stock = 80 + (idx * 37) % 420
        # 销量落在 800~8000：贴近真实电商分布。
        # 上限不能太高——种子数据里有 4.5 万销量的商品，
        # 新批次若远低于它，按销量排序时会被全部挤出首页。
        sales = 800 + (idx * 613) % 7200
        views = (idx * 29) % 5000
        seed = f"{en}-{idx}"
        image = f"https://picsum.photos/seed/{seed}/600/600"
        subtitle = desc[:58]
        # 换行必须用 MySQL 转义序列 \\n（反斜杠+n 两个字符），
        # 不能用真换行 —— 真换行会让一条 VALUES 记录跨多行，
        # 解析时列数对不上（ERROR 1136 Column count doesn't match）。
        # 换行用 SQL 的 CHAR(10) 拼接，而不是写 "\n"：
        #   - 写真换行会让一条 VALUES 记录跨行，触发 ERROR 1136 列数不匹配
        #   - 写 "\n" 转义序列虽然能插入，但存进库是字面两字符，
        #     前端 {{ }} 插值不解析，页面会直接显示 "\n"
        # CHAR(10) 两头都躲开，库里存的是标准换行符。
        desc_full = (
            f"CONCAT('{zh}（虚构演示品牌）{cat_name}，型号 {model}。', "
            f"CHAR(10), '主要参数：{desc}。', CHAR(10), "
            f"'本商品为演示数据，参数取自该品类真实产品的常见规格，价格参考市场行情。')"
        )

        prod_rows.append(
            f"(NULL, {cid}, {esc(name)}, {esc(subtitle)}, {desc_full}, "
            f"{esc(image)}, {dec(price)}, {dec(origin)}, {stock}, {sales}, "
            f"{views}, 1, 0, NOW())"
        )
        stats[cid] += 1

    return prod_rows, stats


